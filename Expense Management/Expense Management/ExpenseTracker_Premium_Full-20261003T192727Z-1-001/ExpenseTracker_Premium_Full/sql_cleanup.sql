-- Run this in phpMyAdmin after selecting the `expense` database.
CREATE DATABASE IF NOT EXISTS expense CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE expense;

CREATE TABLE IF NOT EXISTS reg_users (
  reg_id INT NOT NULL AUTO_INCREMENT,
  user_name VARCHAR(255) NOT NULL UNIQUE,
  user_pass VARCHAR(255) NOT NULL,
  user_pic VARCHAR(255) DEFAULT NULL,
  is_admin TINYINT(1) NOT NULL DEFAULT 0,
  PRIMARY KEY(reg_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE IF NOT EXISTS expense_info (
  item_id INT NOT NULL AUTO_INCREMENT,
  user_id INT NOT NULL,
  item_name VARCHAR(255) NOT NULL,
  item_price DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  item_date DATE NOT NULL,
  item_details TEXT DEFAULT NULL,
  PRIMARY KEY(item_id),
  KEY idx_expense_user_date(user_id,item_date),
  CONSTRAINT fk_expense_user FOREIGN KEY(user_id) REFERENCES reg_users(reg_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- Remove old/demo expenses. This does NOT remove users.
DELETE FROM expense_info;

